    public static string Lookup(string key, string language)
    {
        // 漏翻一条不该让程序起不来：泰文取不到回落英文，英文取不到回落中文，
        // 都没有就把键名原样返回——界面上露出一个明显的占位串，比空白更容易发现。
        if (!Table.TryGetValue(key, out var entry))
        {
            return key;
        }

        if (language == Loc.Thai && StringsThai.TryGet(key, out var thai))
        {
            return thai;
        }

        return language != Loc.Chinese && !string.IsNullOrEmpty(entry.En) ? entry.En : entry.Zh;
    }

